
import { GoogleGenAI, Type } from "@google/genai";
import { VideoAnalysisResult } from "../types";

const ai = new GoogleGenAI({ apiKey: process.env.API_KEY || '' });

export const analyzeVideo = async (
  base64Data: string,
  mimeType: string
): Promise<VideoAnalysisResult> => {
  const prompt = `
    Проведи глубокий анализ этого видео и выдай результат строго на русском языке.
    Твоя задача — понять, как сделано видео, и превратить данные в чёткую структуру.

    Этап 1: Семантический анализ
    — Разбей сюжет на смысловые блоки: Хук, Завязка, Основная часть, Кульминация, CTA (призыв к действию).
    — Опиши кратко каждый блок в 1–2 предложениях.

    Этап 2: Анализ стиля (Tone of Voice)
    — Определи скорость речи (слов в минуту), часто встречающиеся фразы или слова-паразиты, эмоциональную окраску.

    Этап 3: Visual Context (визуальный анализ)
    — Определи обстановку (улица, студия и т.д.) и тип видео (монолог, динамичная нарезка и т.п.).

    Этап 4: Технические детали
    — Транскрибируй всю речь (ASR).
    — Извлеки ключевые кадры (keyframes) с таймкодами.

    Верни ответ СТРОГО в формате JSON со следующей структурой:
    {
      "transcription": "текст всей речи",
      "keyframes": [{"timestamp": "0:00", "description": "описание"}],
      "summary": "краткое резюме всего видео",
      "detectedLanguage": "язык оригинала",
      "структура_видео": [{"блок": "Хук", "описание": "..."}],
      "стиль_речи": {
        "скорость_речи": "...",
        "паттерны": "частые фразы/паразиты",
        "эмоциональный_тон": "..."
      },
      "визуальный_контекст": {
        "обстановка": "...",
        "тип_видео": "..."
      }
    }
  `;

  try {
    const response = await ai.models.generateContent({
      model: "gemini-3-flash-preview",
      contents: {
        parts: [
          { inlineData: { data: base64Data, mimeType } },
          { text: prompt }
        ]
      },
      config: {
        responseMimeType: "application/json"
      }
    });

    const resultText = response.text || "{}";
    return JSON.parse(resultText) as VideoAnalysisResult;
  } catch (error) {
    console.error("Gemini Analysis Error:", error);
    throw new Error("Не удалось проанализировать видео. Убедитесь, что файл не слишком большой и содержит аудио/видео данные.");
  }
};

export const generateScriptBasedOnStyle = async (
  stylePassport: VideoAnalysisResult,
  topic: string
): Promise<string> => {
  const prompt = `
    Ты — экспертный режиссер и сценарист. Твоя задача — написать посекундный сценарий для нового видео на тему: "${topic}".
    Опирайся на "Паспорт стиля" оригинального видео, но адаптируй его под новую тему.

    ДАННЫЕ ПАСПОРТА СТИЛЯ:
    1. Структура: ${stylePassport.структура_видео.map(s => s.блок).join(' -> ')}
    2. Скорость речи: ${stylePassport.стиль_речи.скорость_речи}
    3. Эмоциональный тон: ${stylePassport.стиль_речи.эмоциональный_тон}
    4. Характерные фразы: ${stylePassport.стиль_речи.паттерны}
    5. Визуальный стиль: ${stylePassport.визуальный_контекст.тип_видео}, темп и ракурсы как в оригинале.

    ПРАВИЛА ГЕНЕРАЦИИ:
    1. СТРОГО НЕ КОПИРУЙ визуальные объекты из старого видео (если там была стройка, не используй её для темы про кофе).
    2. Создавай НОВЫЕ визуальные сцены, соответствующие новой теме ("${topic}"), но сохраняй стиль съемки (ракурсы, динамику, монтаж).
    3. Реплики (Текст) должны звучать в типичном для автора тоне и темпе, используя его фразы-паразиты и словечки.
    4. Длина сценария: 30-60 секунд.
    5. Разбей на блоки по 5-10 секунд.
    6. Формат вывода — строго на русском языке:

    [00:00–00:05]
    Кадр: [описание визуала: ракурс, действие, монтажный прием]
    Текст: [фраза в стиле автора]

    [00:05–00:10]
    Кадр: ...
    Текст: ...

    (и так далее до конца структуры)
  `;

  try {
    const response = await ai.models.generateContent({
      model: "gemini-3-flash-preview",
      contents: prompt
    });

    return response.text || "Ошибка генерации сценария.";
  } catch (error) {
    console.error("Gemini Script Generation Error:", error);
    throw new Error("Не удалось сгенерировать сценарий.");
  }
};
